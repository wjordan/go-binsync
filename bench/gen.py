#!/usr/bin/env python3
"""gen.py VARIANT — write variant-dependent source files for bench/testsrv.

Variants (each is exactly one source-level change relative to its parent):
  v1  : baseline
  v2s : one string constant changed, same length   ("hello world" -> "hello there")
  v2l : one string constant changed, +3 bytes      ("hello world" -> "hello world!!!")
  v2c : one line of code added in a handler        (w.Header().Set("X-Foo","bar"))
  v2p : one new exported func in internal/util, called from the handler
  v3  : v2c + v2p
  v4  : v3 + one-line change in internal/third
  v5  : v4 + a "multi-package release": 3 more edits in handlers.go, a new route
        (/fourth) and a new JSON-encoded struct field in main.go, a new package
        internal/fourth (uses encoding/base64, hash/crc32, sort) called from the new
        handler, new funcs + a code change in internal/util and internal/third, and two
        string constants changed to different lengths (greeting +6 B, third prefix +4 B)
"""
import os, sys

V = sys.argv[1]
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "testsrv")

greeting = {"v2s": "hello there", "v2l": "hello world!!!", "v5": "hello, world (v5)"}.get(V, "hello world")
header_line = '\tw.Header().Set("X-Foo", "bar")\n' if V in ("v2c", "v3", "v4", "v5") else ""
use_extra = V in ("v2p", "v3", "v4", "v5")
extra_call = '\ts += util.Extra(r.URL.RawQuery)\n' if use_extra else ""
V5 = V == "v5"
if V5:  # edit 1-3 in handlers.go: a second header, a slug in the greeting, a new handler
    header_line += '\tw.Header().Set("Cache-Control", "no-store")\n'
    extra_call += '\tif slug := util.Slug(r.URL.Path); slug != "" {\n\t\ts += " #" + slug\n\t}\n'
fourth_import = '\t"binsync-bench/internal/fourth"\n' if V5 else ""
fourth_handler = '''
// fourthHandler is new in v5: checksums the query string via internal/fourth.
func fourthHandler(w http.ResponseWriter, r *http.Request) {
\treqCounter.WithLabelValues("/fourth").Inc()
\tsum := fourth.Digest([]byte(r.URL.RawQuery), 3)
\tfmt.Fprintf(w, "%s %s\\n", sum.Hex, third.Tag(sum.Words))
}
''' if V5 else ""

handlers = f'''// Code generated by bench/gen.py ({V}); DO NOT EDIT.
package main

import (
\t"fmt"
\t"net/http"

{fourth_import}\t"binsync-bench/internal/third"
\t"binsync-bench/internal/util"
)

const greeting = "{greeting}"

func helloHandler(w http.ResponseWriter, r *http.Request) {{
\treqCounter.WithLabelValues("/").Inc()
{header_line}\ts := util.Shout(greeting)
{extra_call}\ts += third.Suffix(r.Header.Get("X-Request-Id"))
\tfmt.Fprintln(w, s)
}}
{fourth_handler}'''

extra_fn = '''
// Extra is new in v2p.
func Extra(q string) string {
\tif q == "" {
\t\treturn ""
\t}
\treturn " [" + strings.ToLower(q) + "]"
}
''' if use_extra else ""

repeat_body = ('''\tvar b strings.Builder
\tb.Grow(n * (len(s) + 1))
\tfor i := 0; i < n; i++ {
\t\tif i > 0 {
\t\t\tb.WriteByte(',')
\t\t}
\t\tb.WriteString(s)
\t}
\treturn b.String()
''' if V5 else '''\tparts := make([]string, n)
\tfor i := range parts {
\t\tparts[i] = s
\t}
\treturn strings.Join(parts, ",")
''')
slug_fn = '''
// Slug is new in v5: lower-cases p and keeps [a-z0-9-] only.
func Slug(p string) string {
\tvar b strings.Builder
\tfor _, c := range strings.ToLower(strings.Trim(p, "/")) {
\t\tif (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '-' {
\t\t\tb.WriteRune(c)
\t\t}
\t}
\treturn b.String()
}
''' if V5 else ""

util = f'''// Code generated by bench/gen.py ({V}); DO NOT EDIT.
package util

import "strings"

// Shout upper-cases s and appends an exclamation mark.
func Shout(s string) string {{
\treturn strings.ToUpper(s) + "!"
}}

// Repeat repeats s n times joined by a comma.
func Repeat(s string, n int) string {{
{repeat_body}}}
{extra_fn}{slug_fn}'''

third_line = {"v4": '\treturn " (req " + id + ", v4)"\n', "v5": '\treturn " (request " + id + ", v5)"\n'}.get(V, '\treturn " (req " + id + ")"\n')
tag_fn = '''
// Tag is new in v5.
func Tag(words []string) string {
\tif len(words) == 0 {
\t\treturn "-"
\t}
\treturn "[" + words[0] + "+" + fmt.Sprint(len(words)-1) + "]"
}
''' if V5 else ""
third_import = 'import "fmt"\n\n' if V5 else ""
third = f'''// Code generated by bench/gen.py ({V}); DO NOT EDIT.
package third

{third_import}// Suffix formats the request id for the greeting line.
func Suffix(id string) string {{
\tif id == "" {{
\t\treturn ""
\t}}
{third_line}}}
{tag_fn}'''

fourth = f'''// Code generated by bench/gen.py ({V}); DO NOT EDIT.
// Package fourth is new in v5.
package fourth

import (
\t"encoding/base64"
\t"hash/crc32"
\t"sort"
\t"strings"
)

// Sum is a JSON-encodable digest of an input.
type Sum struct {{
\tHex   string   `json:"hex"`
\tWords []string `json:"words,omitempty"`
\tN     int      `json:"n"`
}}

// Digest crc32s b and returns its base64 form plus the n longest words in b.
func Digest(b []byte, n int) Sum {{
\tc := crc32.Checksum(b, crc32.MakeTable(crc32.Castagnoli))
\tvar raw [4]byte
\traw[0], raw[1], raw[2], raw[3] = byte(c>>24), byte(c>>16), byte(c>>8), byte(c)
\twords := strings.FieldsFunc(string(b), func(r rune) bool {{ return r == '&' || r == '=' || r == ' ' }})
\tsort.SliceStable(words, func(i, j int) bool {{ return len(words[i]) > len(words[j]) }})
\tif len(words) > n {{
\t\twords = words[:n]
\t}}
\treturn Sum{{Hex: base64.RawURLEncoding.EncodeToString(raw[:]), Words: words, N: len(b)}}
}}
'''

for rel, body in [("handlers.go", handlers), ("internal/util/util.go", util), ("internal/third/third.go", third)]:
    p = os.path.join(ROOT, rel)
    with open(p, "w") as f:
        f.write(body)
fp = os.path.join(ROOT, "internal/fourth/fourth.go")
if V5:
    os.makedirs(os.path.dirname(fp), exist_ok=True)
    open(fp, "w").write(fourth)
elif os.path.exists(fp):
    os.remove(fp); os.rmdir(os.path.dirname(fp))

# main.go is hand-written; v5 adds a JSON-encoded struct field and a route (reverted otherwise).
mp = os.path.join(ROOT, "main.go")
m = open(mp).read()
FIELD_OLD = '\tBio     string   `xml:"bio" json:"bio"`\n}'
FIELD_NEW = '\tBio     string   `xml:"bio" json:"bio"`\n\tEmail   string   `xml:"email,omitempty" json:"email,omitempty"` // v5\n}'
ROUTE_OLD = '\tr.Get("/", helloHandler)\n'
ROUTE_NEW = '\tr.Get("/", helloHandler)\n\tr.Get("/fourth", fourthHandler) // v5\n'
m2 = m.replace(FIELD_NEW, FIELD_OLD).replace(ROUTE_NEW, ROUTE_OLD)
if V5:
    m2 = m2.replace(FIELD_OLD, FIELD_NEW).replace(ROUTE_OLD, ROUTE_NEW)
if m2 != m:
    open(mp, "w").write(m2)
print(f"generated variant {V}")
