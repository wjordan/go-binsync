#!/usr/bin/env python3
"""gen.py VARIANT — write variant-dependent source files for bench/testsrv.

Variants (each is exactly one source-level change relative to its parent):
  v1  : baseline
  v2s : one string constant changed, same length   ("hello world" -> "hello there")
  v2l : one string constant changed, +3 bytes      ("hello world" -> "hello world!!!")
  v2c : one line of code added in a handler        (w.Header().Set("X-Foo","bar"))
  v2p : one new exported func in internal/util, called from the handler
  v3  : v2c + v2p
  v4  : v3 + one-line change in internal/third
"""
import os, sys

V = sys.argv[1]
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "testsrv")

greeting = {"v2s": "hello there", "v2l": "hello world!!!"}.get(V, "hello world")
header_line = '\tw.Header().Set("X-Foo", "bar")\n' if V in ("v2c", "v3", "v4") else ""
use_extra = V in ("v2p", "v3", "v4")
extra_call = '\ts += util.Extra(r.URL.RawQuery)\n' if use_extra else ""

handlers = f'''// Code generated by bench/gen.py ({V}); DO NOT EDIT.
package main

import (
\t"fmt"
\t"net/http"

\t"binsync-bench/internal/third"
\t"binsync-bench/internal/util"
)

const greeting = "{greeting}"

func helloHandler(w http.ResponseWriter, r *http.Request) {{
\treqCounter.WithLabelValues("/").Inc()
{header_line}\ts := util.Shout(greeting)
{extra_call}\ts += third.Suffix(r.Header.Get("X-Request-Id"))
\tfmt.Fprintln(w, s)
}}
'''

extra_fn = '''
// Extra is new in v2p.
func Extra(q string) string {
\tif q == "" {
\t\treturn ""
\t}
\treturn " [" + strings.ToLower(q) + "]"
}
''' if use_extra else ""

util = f'''// Code generated by bench/gen.py ({V}); DO NOT EDIT.
package util

import "strings"

// Shout upper-cases s and appends an exclamation mark.
func Shout(s string) string {{
\treturn strings.ToUpper(s) + "!"
}}

// Repeat repeats s n times joined by a comma.
func Repeat(s string, n int) string {{
\tparts := make([]string, n)
\tfor i := range parts {{
\t\tparts[i] = s
\t}}
\treturn strings.Join(parts, ",")
}}
{extra_fn}'''

third_line = '\treturn " (req " + id + ", v4)"\n' if V == "v4" else '\treturn " (req " + id + ")"\n'
third = f'''// Code generated by bench/gen.py ({V}); DO NOT EDIT.
package third

// Suffix formats the request id for the greeting line.
func Suffix(id string) string {{
\tif id == "" {{
\t\treturn ""
\t}}
{third_line}}}
'''

for rel, body in [("handlers.go", handlers), ("internal/util/util.go", util), ("internal/third/third.go", third)]:
    p = os.path.join(ROOT, rel)
    with open(p, "w") as f:
        f.write(body)
print(f"generated variant {V}")
